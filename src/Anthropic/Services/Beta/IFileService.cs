using System;
using System.Threading;
using System.Threading.Tasks;
using Anthropic.Core;
using Anthropic.Models;
using Anthropic.Models.Beta.Files;
using Files = Anthropic.Models.Files;

namespace Anthropic.Services.Beta;

/// <summary>
/// NOTE: Do not inherit from this type outside the SDK unless you're okay with breaking
/// changes in non-major versions. We may add new methods in the future that cause
/// existing derived classes to break.
/// </summary>
public interface IFileService
{
    /// <summary>
    /// Returns a view of this service that provides access to raw HTTP responses
    /// for each method.
    /// </summary>
    IFileServiceWithRawResponse WithRawResponse { get; }

    /// <summary>
    /// Returns a view of this service with the given option modifications applied.
    ///
    /// <para>The original service is not modified.</para>
    /// </summary>
    IFileService WithOptions(Func<ClientOptions, ClientOptions> modifier);

    /// <summary>
    /// List Files
    /// </summary>
    /// <exception cref="AnthropicClaudeCodeKeyCreatorNotMemberException">
    /// The API key belongs to the Claude Code workspace, and the user who created it is
    /// no longer a member of the organization or of that workspace.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyDisabledException">
    /// The workspace's customer-managed encryption key is disabled or revoked.
    /// Re-enable the key, then retry.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyNetworkBlockedException">
    /// The key management service's network access controls blocked the request to the
    /// workspace's customer-managed encryption key. The key itself may be healthy.
    /// </exception>
    /// <exception cref="AnthropicOrganizationOnHoldException">
    /// Anthropic has disabled the organization for trust and safety reasons. An
    /// organization disabled for any other reason, such as billing, does not get this
    /// code. `appeal_url`, when present, is where the organization can appeal.
    /// </exception>
    Task<FileListPage> List(
        FileListParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Delete File
    /// </summary>
    /// <exception cref="AnthropicClaudeCodeKeyCreatorNotMemberException">
    /// The API key belongs to the Claude Code workspace, and the user who created it is
    /// no longer a member of the organization or of that workspace.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyDisabledException">
    /// The workspace's customer-managed encryption key is disabled or revoked.
    /// Re-enable the key, then retry.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyNetworkBlockedException">
    /// The key management service's network access controls blocked the request to the
    /// workspace's customer-managed encryption key. The key itself may be healthy.
    /// </exception>
    /// <exception cref="AnthropicOrganizationOnHoldException">
    /// Anthropic has disabled the organization for trust and safety reasons. An
    /// organization disabled for any other reason, such as billing, does not get this
    /// code. `appeal_url`, when present, is where the organization can appeal.
    /// </exception>
    Task<BetaDeletedFile> Delete(
        FileDeleteParams parameters,
        CancellationToken cancellationToken = default
    );

    /// <inheritdoc cref="Delete(FileDeleteParams, CancellationToken)"/>
    Task<BetaDeletedFile> Delete(
        string fileID,
        FileDeleteParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Download File
    ///
    /// <para>It's the caller's responsibility to dispose the returned response.</para>
    /// </summary>
    /// <exception cref="AnthropicClaudeCodeKeyCreatorNotMemberException">
    /// The API key belongs to the Claude Code workspace, and the user who created it is
    /// no longer a member of the organization or of that workspace.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyDisabledException">
    /// The workspace's customer-managed encryption key is disabled or revoked.
    /// Re-enable the key, then retry.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyNetworkBlockedException">
    /// The key management service's network access controls blocked the request to the
    /// workspace's customer-managed encryption key. The key itself may be healthy.
    /// </exception>
    /// <exception cref="Files::AnthropicFileNotDownloadableException">
    /// The file has `downloadable: false`. Only files generated by a tool, such as the
    /// code execution tool, can be downloaded.
    /// </exception>
    /// <exception cref="AnthropicOrganizationOnHoldException">
    /// Anthropic has disabled the organization for trust and safety reasons. An
    /// organization disabled for any other reason, such as billing, does not get this
    /// code. `appeal_url`, when present, is where the organization can appeal.
    /// </exception>
    /// <exception cref="Files::AnthropicFileExpiredException">
    /// The file's `expires_at` has passed, so its content is no longer available.
    /// </exception>
    Task<HttpResponse> Download(
        FileDownloadParams parameters,
        CancellationToken cancellationToken = default
    );

    /// <inheritdoc cref="Download(FileDownloadParams, CancellationToken)"/>
    Task<HttpResponse> Download(
        string fileID,
        FileDownloadParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Get File Metadata
    /// </summary>
    /// <exception cref="AnthropicClaudeCodeKeyCreatorNotMemberException">
    /// The API key belongs to the Claude Code workspace, and the user who created it is
    /// no longer a member of the organization or of that workspace.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyDisabledException">
    /// The workspace's customer-managed encryption key is disabled or revoked.
    /// Re-enable the key, then retry.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyNetworkBlockedException">
    /// The key management service's network access controls blocked the request to the
    /// workspace's customer-managed encryption key. The key itself may be healthy.
    /// </exception>
    /// <exception cref="AnthropicOrganizationOnHoldException">
    /// Anthropic has disabled the organization for trust and safety reasons. An
    /// organization disabled for any other reason, such as billing, does not get this
    /// code. `appeal_url`, when present, is where the organization can appeal.
    /// </exception>
    Task<BetaFileMetadata> RetrieveMetadata(
        FileRetrieveMetadataParams parameters,
        CancellationToken cancellationToken = default
    );

    /// <inheritdoc cref="RetrieveMetadata(FileRetrieveMetadataParams, CancellationToken)"/>
    Task<BetaFileMetadata> RetrieveMetadata(
        string fileID,
        FileRetrieveMetadataParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Upload File
    /// </summary>
    /// <exception cref="AnthropicClaudeCodeKeyCreatorNotMemberException">
    /// The API key belongs to the Claude Code workspace, and the user who created it is
    /// no longer a member of the organization or of that workspace.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyDisabledException">
    /// The workspace's customer-managed encryption key is disabled or revoked.
    /// Re-enable the key, then retry.
    /// </exception>
    /// <exception cref="AnthropicCmekKeyNetworkBlockedException">
    /// The key management service's network access controls blocked the request to the
    /// workspace's customer-managed encryption key. The key itself may be healthy.
    /// </exception>
    /// <exception cref="AnthropicOrganizationOnHoldException">
    /// Anthropic has disabled the organization for trust and safety reasons. An
    /// organization disabled for any other reason, such as billing, does not get this
    /// code. `appeal_url`, when present, is where the organization can appeal.
    /// </exception>
    /// <exception cref="Files::AnthropicStorageQuotaExceededException">
    /// The organization's file storage quota is exhausted. Delete files to free up
    /// space, then retry the upload.
    /// </exception>
    Task<BetaFileMetadata> Upload(
        FileUploadParams parameters,
        CancellationToken cancellationToken = default
    );
}

/// <summary>
/// A view of <see cref="IFileService"/> that provides access to raw
/// HTTP responses for each method.
/// </summary>
public interface IFileServiceWithRawResponse
{
    /// <summary>
    /// Returns a view of this service with the given option modifications applied.
    ///
    /// <para>The original service is not modified.</para>
    /// </summary>
    IFileServiceWithRawResponse WithOptions(Func<ClientOptions, ClientOptions> modifier);

    /// <summary>
    /// Returns a raw HTTP response for <c>get /v1/files</c>, but is otherwise the
    /// same as <see cref="IFileService.List(FileListParams?, CancellationToken)"/>.
    /// </summary>
    Task<HttpResponse<FileListPage>> List(
        FileListParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Returns a raw HTTP response for <c>delete /v1/files/{file_id}</c>, but is otherwise the
    /// same as <see cref="IFileService.Delete(FileDeleteParams, CancellationToken)"/>.
    /// </summary>
    Task<HttpResponse<BetaDeletedFile>> Delete(
        FileDeleteParams parameters,
        CancellationToken cancellationToken = default
    );

    /// <inheritdoc cref="Delete(FileDeleteParams, CancellationToken)"/>
    Task<HttpResponse<BetaDeletedFile>> Delete(
        string fileID,
        FileDeleteParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Returns a raw HTTP response for <c>get /v1/files/{file_id}/content</c>, but is otherwise the
    /// same as <see cref="IFileService.Download(FileDownloadParams, CancellationToken)"/>.
    /// </summary>
    Task<HttpResponse> Download(
        FileDownloadParams parameters,
        CancellationToken cancellationToken = default
    );

    /// <inheritdoc cref="Download(FileDownloadParams, CancellationToken)"/>
    Task<HttpResponse> Download(
        string fileID,
        FileDownloadParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Returns a raw HTTP response for <c>get /v1/files/{file_id}</c>, but is otherwise the
    /// same as <see cref="IFileService.RetrieveMetadata(FileRetrieveMetadataParams, CancellationToken)"/>.
    /// </summary>
    Task<HttpResponse<BetaFileMetadata>> RetrieveMetadata(
        FileRetrieveMetadataParams parameters,
        CancellationToken cancellationToken = default
    );

    /// <inheritdoc cref="RetrieveMetadata(FileRetrieveMetadataParams, CancellationToken)"/>
    Task<HttpResponse<BetaFileMetadata>> RetrieveMetadata(
        string fileID,
        FileRetrieveMetadataParams? parameters = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Returns a raw HTTP response for <c>post /v1/files</c>, but is otherwise the
    /// same as <see cref="IFileService.Upload(FileUploadParams, CancellationToken)"/>.
    /// </summary>
    Task<HttpResponse<BetaFileMetadata>> Upload(
        FileUploadParams parameters,
        CancellationToken cancellationToken = default
    );
}
